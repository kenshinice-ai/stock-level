#!/usr/bin/env node
// Builds src/officeworks/postcodes-au.mjs (postcode -> approximate centre)
// from the GeoNames postal code dump for Australia:
//   https://download.geonames.org/export/zip/AU.zip  (CC BY 4.0, www.geonames.org)
//
//   node scripts/build-au-postcodes.mjs path/to/AU.txt

import fs from "node:fs";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-au-postcodes.mjs path/to/AU.txt");
  process.exit(1);
}

// AU.txt columns: country, postcode, place, state name, state code, ..., lat, lng, accuracy
const byPostcode = new Map();
for (const line of fs.readFileSync(input, "utf8").split("\n")) {
  const cols = line.split("\t");
  if (cols.length < 11) continue;
  const postcode = cols[1].padStart(4, "0");
  const state = cols[4];
  const lat = Number(cols[9]);
  const lng = Number(cols[10]);
  if (!/^\d{4}$/.test(postcode) || !Number.isFinite(lat) || !Number.isFinite(lng)) continue;
  const entry = byPostcode.get(postcode) || { lat: 0, lng: 0, n: 0, state };
  entry.lat += lat;
  entry.lng += lng;
  entry.n += 1;
  byPostcode.set(postcode, entry);
}

const rows = [...byPostcode]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([pc, e]) => `${pc}${e.state},${(e.lat / e.n).toFixed(3)},${(e.lng / e.n).toFixed(3)}`);

const out = `// Generated by scripts/build-au-postcodes.mjs - do not edit by hand.
// Australian postcode centres (mean of GeoNames places per postcode, ~100 m precision).
// Data: GeoNames (www.geonames.org), licensed CC BY 4.0.
// Format: "<postcode><STATE>,<lat>,<lng>" separated by ";".

const DATA =
  "${rows.join(";")}";

let index = null;

// Returns { postcode, state, lat, lng } or null.
export function lookupPostcode(postcode) {
  if (!index) {
    index = new Map();
    for (const row of DATA.split(";")) {
      const [head, lat, lng] = row.split(",");
      index.set(head.slice(0, 4), { postcode: head.slice(0, 4), state: head.slice(4), lat: Number(lat), lng: Number(lng) });
    }
  }
  return index.get(String(postcode || "").padStart(4, "0")) || null;
}

export const POSTCODE_COUNT = ${rows.length};
`;

fs.writeFileSync(new URL("../src/officeworks/postcodes-au.mjs", import.meta.url), out);
console.log(`Wrote ${rows.length} postcodes.`);
